-- 4. FUNÇÕES DE APOIO (quem sou eu / o que posso)
-- ---------------------------------------------------------------------
create or replace function public.eu_aprovado() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from perfis where id = auth.uid() and status = 'aprovado')
$$;

create or replace function public.meu_login() returns text
language sql stable security definer set search_path = public as $$
  select login from perfis where id = auth.uid() and status = 'aprovado'
$$;

-- admin vale como todas as funções nas checagens do servidor
create or replace function public.tenho_funcao(variadic f text[]) returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from perfis where id = auth.uid() and status = 'aprovado'
                and (funcoes && f or 'admin' = any(funcoes)))
$$;

create or replace function public.sou_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from perfis where id = auth.uid() and status = 'aprovado' and 'admin' = any(funcoes))
$$;

create or replace function public.acesso_obra(o bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.sou_admin() or exists(
    select 1 from obra_acessos a join perfis p on p.login = a.login
    where p.id = auth.uid() and p.status = 'aprovado' and a.obra_id = o)
$$;

