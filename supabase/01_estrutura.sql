create or replace function public.laudo_recebido(p_id bigint, p_obs text, p_anexos jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v jsonb; v_obra bigint;
begin
  select id_obra into v_obra from laudos where id = p_id;
  if v_obra is null then raise exception 'laudo não encontrado'; end if;
  if not (tenho_funcao('rc') and acesso_obra(v_obra)) then raise exception 'sem_permissao'; end if;
  update laudos set status = 'recebido', recebido_em = now(), recebido_por = meu_login(),
         obs = left(coalesce(p_obs,''),1000), anexos = p_anexos
   where id = p_id returning to_jsonb(laudos.*) into v;
  return v;
end $$;
revoke execute on function public.laudo_recebido(bigint,text,jsonb) from public, anon;
grant execute on function public.laudo_recebido(bigint,text,jsonb) to authenticated;

