-- 5. CADASTRO NOVO → PERFIL "PENDENTE" (o admin aprova no app)
-- ---------------------------------------------------------------------
create or replace function public.novo_usuario() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_email text := lower(new.email);
  v_login text;
  v_nome  text;
  v_admin boolean;
begin
  v_login := case when v_email like '%@rottasconstrutora.com.br' then split_part(v_email,'@',1) else v_email end;
  if exists(select 1 from perfis where login = v_login) then v_login := v_email; end if;
  v_nome  := nullif(trim(coalesce(new.raw_user_meta_data->>'nome','')),'');
  if v_nome is null then v_nome := initcap(replace(split_part(v_login,'@',1),'.',' ')); end if;
  v_admin := exists(select 1 from admins_iniciais where lower(email) = v_email);

  insert into perfis(id,email,login,nome,status,funcoes,aprovado_em,aprovado_por)
  values (new.id, v_email, v_login, v_nome,
          case when v_admin then 'aprovado' else 'pendente' end,
          case when v_admin then array(select codigo from funcoes order by ordem) else '{}' end,
          case when v_admin then now() end,
          case when v_admin then 'automático' end);
  return new;
end $$;

