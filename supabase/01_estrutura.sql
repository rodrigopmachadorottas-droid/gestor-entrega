update public.clientes c set id_obra = x.o
  from (select id_cliente, min(id_obra) as o from public.unidades where id_cliente is not null group by id_cliente) x
 where x.id_cliente = c.id and c.id_obra is null;

do $$
declare r record; v bigint; n int := 0;
begin
  for r in select u.id_cliente, u.id_obra from public.unidades u join public.clientes c on c.id = u.id_cliente
            where c.id_obra is not null and u.id_obra <> c.id_obra group by 1, 2 loop
    insert into public.clientes(id_obra, nome, email, telefone, criado_por, criado_em)
      select r.id_obra, nome, email, telefone, criado_por, criado_em from public.clientes where id = r.id_cliente
      returning id into v;
    update public.unidades set id_cliente = v where id_cliente = r.id_cliente and id_obra = r.id_obra;
    n := n + 1;
  end loop;
  raise notice '% cópia(s) de cliente criada(s) para obras extras', n;
end $$;

